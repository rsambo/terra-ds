#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const light = require('../dist/tokens/tailwind.theme.json');
const dark = require('../dist/tokens/tailwind.dark.theme.json');

const lightColors = light.theme.extend.colors;
const darkColors = dark.theme.extend.colors;

const spacing = light.theme.extend.spacing;
const borderRadius = light.theme.extend.borderRadius;
const fontFamily = light.theme.extend.fontFamily;
const fontSize = light.theme.extend.fontSize;

// Read DESIGN.md frontmatter to supplement dropped lineHeight / letterSpacing
function parseDesignMd() {
  const designPath = path.join(__dirname, '../DESIGN.md');
  const raw = fs.readFileSync(designPath, 'utf-8');
  // Extract YAML frontmatter between --- lines
  const match = raw.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return { typography: {} };
  const yaml = match[1];
  // Simple YAML parser for the nested typography block we need
  const lines = yaml.split('\n');
  const typography = {};
  let currentRole = null;
  let inTypography = false;
  for (const line of lines) {
    const trimmed = line.trimEnd();
    if (trimmed === 'typography:') {
      inTypography = true;
      continue;
    }
    if (!inTypography) continue;
    // Exit typography block when we hit another top-level key (no indent)
    if (/^[a-zA-Z]/.test(trimmed) && !trimmed.startsWith(' ') && !trimmed.startsWith('  ')) {
      inTypography = false;
      continue;
    }
    // Role header: "  display-lg:"
    const roleMatch = trimmed.match(/^(\s+)([\w-]+):\s*$/);
    if (roleMatch) {
      currentRole = roleMatch[2];
      typography[currentRole] = {};
      continue;
    }
    // Property: "    fontFamily: 'Inter'"
    const propMatch = trimmed.match(/^(\s+)(\w+):\s*(.+)$/);
    if (propMatch && currentRole) {
      let val = propMatch[3].trim();
      // Remove surrounding quotes
      if ((val.startsWith("'") && val.endsWith("'")) || (val.startsWith('"') && val.endsWith('"'))) {
        val = val.slice(1, -1);
      }
      typography[currentRole][propMatch[2]] = val;
    }
  }
  return { typography };
}

const designData = parseDesignMd();

const toVar = (name) => `--color-${name}`;

let css = '/* Generated by scripts/generate-css-vars.js — do not edit */\n\n';

// :root block — light colors + all theme-agnostic tokens
css += ':root {\n';
css += '  /* colors (light) */\n';
for (const [name, value] of Object.entries(lightColors)) {
  css += `  ${toVar(name)}: ${value};\n`;
}

css += '\n  /* spacing */\n';
for (const [name, value] of Object.entries(spacing)) {
  css += `  --spacing-${name}: ${value};\n`;
}

css += '\n  /* border radius */\n';
for (const [name, value] of Object.entries(borderRadius)) {
  css += `  --rounded-${name}: ${value};\n`;
}

css += '\n  /* typography */\n';
for (const role of Object.keys(fontFamily)) {
  const family = fontFamily[role];
  const sizeEntry = fontSize[role];
  const sizeValue = Array.isArray(sizeEntry) ? sizeEntry[0] : sizeEntry;
  const sizeMeta = Array.isArray(sizeEntry) && sizeEntry[1] ? sizeEntry[1] : {};
  const weight = sizeMeta.fontWeight || '400';

  const designRole = designData.typography[role] || {};
  const lineHeight = designRole.lineHeight || 'normal';
  const letterSpacing = designRole.letterSpacing || sizeMeta.letterSpacing || '0em';

  // fontFamily from export is an array; join with comma
  const familyStr = Array.isArray(family) ? family.join(', ') : family;

  css += `  --font-family-${role}: ${familyStr};\n`;
  css += `  --font-size-${role}: ${sizeValue};\n`;
  css += `  --font-weight-${role}: ${weight};\n`;
  css += `  --line-height-${role}: ${lineHeight};\n`;
  css += `  --letter-spacing-${role}: ${letterSpacing};\n`;
}

css += '}\n\n';

// .dark block — colors only
css += '.dark {\n';
for (const [name, value] of Object.entries(darkColors)) {
  css += `  ${toVar(name)}: ${value};\n`;
}
css += '}\n';

const outPath = path.join(__dirname, '../src/tokens.css');
fs.writeFileSync(outPath, css);
console.log(`Written: src/tokens.css`);
